-- kotlin: kotlinx-coroutines-core/common/test/flow/sharing/SharingStartedTest.kt@1.11.0
local async = require("luastd.async")
local flow = require("luastd.flow")
local runtest = require("luastd_test").runtest

---@async
local function observe(policy)
    local counts = flow.mutable_state_flow(0)
    local commands = async.channel(16)
    local collector = async.launch(function ()
        policy:command(counts):collect(function (command) commands:send(command) end)
    end)
    async.yield()
    return counts, commands, collector
end

---@async
local function expect_command(commands, expected)
    local command = async.with_timeout(2000, function () return commands:receive() end)
    assert.is_equal(expected, command)
end

---@async
local function expect_no_command(commands, delay_ms)
    async.delay(delay_ms)
    local received = commands:try_receive()
    assert.is_false(received)
end

local function stop(collector)
    collector:cancel()
end

describe("SharingStartedTest", function ()
    it("testEagerly", runtest(function (t)
        local _, commands, collector = observe(flow.sharing_started.eagerly())
        expect_command(commands, "START")
        expect_no_command(commands, 10)
        stop(collector)
        t:finish(1)
    end))

    it("testLazily", runtest(function (t)
        local counts, commands, collector = observe(flow.sharing_started.lazily())
        expect_no_command(commands, 10)
        counts:set_value(1)
        expect_command(commands, "START")
        counts:set_value(3)
        counts:set_value(0)
        expect_no_command(commands, 10)
        stop(collector)
        t:finish(1)
    end))

    it("testWhileSubscribed", runtest(function (t)
        local policy = flow.sharing_started.while_subscribed()
        assert.is_true(policy == flow.sharing_started.while_subscribed(0, math.huge))
        local counts, commands, collector = observe(policy)
        counts:set_value(1)
        expect_command(commands, "START")
        counts:set_value(2)
        expect_no_command(commands, 10)
        counts:set_value(0)
        expect_command(commands, "STOP")
        stop(collector)
        t:finish(1)
    end))

    it("testWhileSubscribedExpireImmediately", runtest(function (t)
        local counts, commands, collector = observe(flow.sharing_started.while_subscribed(0, 0))
        counts:set_value(1)
        expect_command(commands, "START")
        counts:set_value(0)
        expect_command(commands, "STOP_AND_RESET_REPLAY_CACHE")
        expect_no_command(commands, 10)
        stop(collector)
        t:finish(1)
    end))

    -- adapted: real delays replace virtual time; resubscribing before the 100 ms
    -- stop timeout cancels it, while the later zero-count interval emits STOP.
    it("testWhileSubscribedWithTimeout", runtest(function (t)
        local counts, commands, collector = observe(flow.sharing_started.while_subscribed(100))
        counts:set_value(1)
        expect_command(commands, "START")
        counts:set_value(0)
        async.delay(40)
        counts:set_value(1)
        expect_no_command(commands, 120)
        counts:set_value(0)
        expect_command(commands, "STOP")
        stop(collector)
        t:finish(1)
    end))

    -- adapted: shortened real delays cover expiration cancellation and reset.
    it("testWhileSubscribedExpiration", runtest(function (t)
        local counts, commands, collector = observe(flow.sharing_started.while_subscribed(0, 100))
        counts:set_value(1)
        expect_command(commands, "START")
        counts:set_value(0)
        expect_command(commands, "STOP")
        async.delay(40)
        counts:set_value(1)
        expect_command(commands, "START")
        expect_no_command(commands, 120)
        counts:set_value(0)
        expect_command(commands, "STOP")
        expect_command(commands, "STOP_AND_RESET_REPLAY_CACHE")
        stop(collector)
        t:finish(1)
    end))

    -- adapted: shortened real delays verify stop timeout, replay expiration,
    -- and that resubscription cancels an expiration already in progress.
    it("testWhileSubscribedStopAndExpiration", runtest(function (t)
        local counts, commands, collector = observe(flow.sharing_started.while_subscribed(100, 80))
        counts:set_value(1)
        expect_command(commands, "START")
        counts:set_value(0)
        async.delay(40)
        counts:set_value(1)
        expect_no_command(commands, 10)
        counts:set_value(0)
        expect_command(commands, "STOP")
        async.delay(30)
        counts:set_value(1)
        expect_command(commands, "START")
        expect_no_command(commands, 90)
        counts:set_value(0)
        expect_command(commands, "STOP")
        expect_command(commands, "STOP_AND_RESET_REPLAY_CACHE")
        stop(collector)
        t:finish(1)
    end))
end)
