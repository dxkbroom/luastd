-- kotlin: kotlinx-coroutines-core/common/test/CoroutinesTest.kt@1.11.0
local async = require("luastd.async")
local luastd_test = require("luastd_test")
local runtest = luastd_test.runtest

describe("CoroutinesTest", function ()
    it("testSimple", runtest(function (t)
        t:expect(1)
        t:finish(2)
    end))

    it("testYield", runtest(function (t)
        t:expect(1)
        async.yield()
        t:finish(2)
    end))

    it("testLaunchAndYieldJoin", runtest(function (t)
        t:expect(1)
        local job = async.launch(function ()
            t:expect(3)
            async.yield()
            t:expect(4)
        end)
        t:expect(2)
        assert.is_true(job:is_active())
        assert.is_false(job:is_completed())
        async.join(job)
        assert.is_false(job:is_active())
        assert.is_true(job:is_completed())
        t:finish(5)
    end))

    -- not-applicable: luastd launch has no CoroutineStart.UNDISPATCHED mode.
    pending("testLaunchUndispatched")

    it("testNested", runtest(function (t)
        t:expect(1)
        local outer = async.launch(function ()
            t:expect(3)
            local inner = async.launch(function () t:expect(5) end)
            t:expect(4)
            async.join(inner)
            t:expect(6)
        end)
        t:expect(2)
        async.join(outer)
        t:finish(7)
    end))

    it("testWaitChild", runtest(function (t)
        t:expect(1)
        async.launch(function ()
            t:expect(3)
            async.yield()
            t:finish(5)
        end)
        t:expect(2)
        async.yield()
        t:expect(4)
    end))

    it("testCancelChildExplicit", runtest(function (t)
        t:expect(1)
        local job = async.launch(function ()
            t:expect(3)
            async.yield()
            t:expect_unreached()
        end)
        t:expect(2)
        async.yield()
        t:expect(4)
        job:cancel()
        t:finish(5)
    end))

    it("testCancelChildWithFinally", runtest(function (t)
        t:expect(1)
        local job = async.launch(function ()
            t:expect(3)
            async.finally(function () async.await_cancellation() end, function ()
                t:expect(6)
            end)
            t:expect_unreached()
        end)
        t:expect(2)
        async.yield()
        t:expect(4)
        job:cancel()
        t:expect(5)
        async.join(job)
        t:finish(7)
    end))

    -- adapted: assert the nested join relationship directly; the executor's
    -- ready-task order differs from Kotlin's sequence of yield expectations.
    it("testWaitNestedChild", runtest(function (t)
        local nested_finished = false
        local parent_finished = false
        local parent = async.launch(function ()
            local child = async.launch(function ()
                async.yield()
                nested_finished = true
            end)
            async.yield()
            async.join(child)
            parent_finished = true
        end)
        assert.is_false(parent:is_completed())
        async.join(parent)
        assert.is_true(nested_finished)
        assert.is_true(parent_finished)
        t:finish(1)
    end))

    it("testExceptionPropagation", runtest({ expected = "TestException" }, function (t)
        t:finish(1)
        error(luastd_test.TestException())
    end))

    -- adapted: model runTest's structured child scope with async.scope; a
    -- failing child cancels the body and propagates its original error.
    it("testCancelParentOnChildException", runtest({ expected = "TestException" }, function (t)
        t:expect(1)
        async.scope(function (scope)
            scope:launch(function ()
                t:finish(3)
                error(luastd_test.TestException())
            end)
            t:expect(2)
            async.yield()
            t:expect_unreached()
        end)
    end))

    -- adapted: nested async.scope propagates child failure, but waits for its
    -- child before exposing the error to the outer test body.
    it("testCancelParentOnNestedException", runtest({ expected = "TestException" }, function (t)
        local failure = luastd_test.TestException()
        local ok, err = pcall(function ()
            async.scope(function (outer)
                outer:launch(function ()
                    async.scope(function (inner)
                        inner:launch(function () error(failure, 0) end)
                        async.yield()
                    end)
                end)
                async.yield()
            end)
        end)
        assert.is_false(ok)
        assert.is_true(rawequal(failure, err))
        t:finish(1)
        error(err, 0)
    end))

    it("testJoinWithFinally", runtest(function (t)
        t:expect(1)
        local job = async.launch(function ()
            t:expect(3)
            async.finally(function () async.await_cancellation() end, function ()
                t:expect(7)
            end)
        end)
        t:expect(2)
        async.yield()
        t:expect(4)
        assert.is_true(job:is_active())
        assert.is_false(job:is_completed())
        job:cancel()
        t:expect(5)
        assert.is_false(job:is_active())
        assert.is_false(job:is_completed())
        t:expect(6)
        async.join(job)
        t:expect(8)
        assert.is_true(job:is_completed())
        t:finish(9)
    end))

    -- adapted: there is no combined cancel_and_join helper or undispatched
    -- start; explicitly cancel then join the started child.
    it("testCancelAndJoin", runtest(function (t)
        t:expect(1)
        local job = async.launch(function ()
            async.finally(function () async.await_cancellation() end, function ()
                t:expect(5)
            end)
        end)
        t:expect(2)
        async.yield()
        t:expect(3)
        job:cancel()
        t:expect(4)
        async.join(job)
        t:finish(6)
    end))

    -- not-applicable: async.join does not rethrow a failed job wrapped in a
    -- CancellationException with its cause; async.await reports the original.
    pending("testCancelAndJoinChildCrash")

    it("testYieldInFinally", runtest({ expected = "TestException" }, function (t)
        async.finally(function ()
            t:expect(1)
            error(luastd_test.TestException())
        end, function ()
            t:expect(2)
            async.yield()
            t:finish(3)
        end)
    end))

    -- not-applicable: luastd has no standalone Job:cancel_children operation;
    -- cancelling a parent Job also cancels the parent itself.
    pending("testCancelAndJoinChildren")

    -- adapted: async.scope supplies structured parent failure and async.finally
    -- runs cleanup non-cancellably; it waits for cleanup before surfacing error.
    it("testParentCrashCancelsChildren", runtest({ expected = "TestException" }, function (t)
        local failure = luastd_test.TestException("Crashed")
        local child
        local cleanup_ran = false
        local ok, err = pcall(function ()
            async.scope(function (parent)
                child = parent:launch(function ()
                    async.finally(function () async.await_cancellation() end, function ()
                        cleanup_ran = true
                        async.yield()
                    end)
                    t:expect_unreached()
                end)
                parent:launch(function () error(failure, 0) end)
                async.yield()
            end)
        end)
        assert.is_false(ok)
        assert.is_true(rawequal(failure, err))
        assert.is_true(child:is_cancelled())
        assert.is_true(cleanup_ran)
        t:finish(1)
        error(err, 0)
    end))

    -- not-applicable: the case requires NonCancellable plus CoroutineStart.ATOMIC
    -- and cancellation causes, none of which are exposed by luastd.
    pending("testNotCancellableChildWithExceptionCancelled")
end)
