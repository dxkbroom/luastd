-- kotlin: kotlinx-coroutines-core/common/test/LaunchLazyTest.kt@1.11.0
local async = require("luastd.async")
local runtest = require("luastd_test").runtest

describe("LaunchLazyTest", function ()
    it(
        "testLaunchAndYieldJoin",
        runtest(function (t)
            t:expect(1)
            local job = async.launch_lazy(function ()
                t:expect(4)
                async.yield()
                t:expect(5)
            end)
            t:expect(2)
            async.yield()
            t:expect(3)
            assert.is_false(job:is_active())
            assert.is_false(job:is_completed())
            async.join(job)
            assert.is_false(job:is_active())
            assert.is_true(job:is_completed())
            t:finish(6)
        end)
    )

    it(
        "testStart",
        runtest(function (t)
            t:expect(1)
            local job = async.launch_lazy(function ()
                t:expect(5)
                async.yield()
                t:expect(7)
            end)
            t:expect(2)
            async.yield()
            t:expect(3)
            assert.is_false(job:is_active())
            assert.is_false(job:is_completed())
            assert.is_true(job:start())
            assert.is_true(job:is_active())
            assert.is_false(job:is_completed())
            assert.is_false(job:start())
            assert.is_true(job:is_active())
            assert.is_false(job:is_completed())
            t:expect(4)
            async.yield()
            t:expect(6)
            assert.is_true(job:is_active())
            assert.is_false(job:is_completed())
            async.yield()
            assert.is_false(job:is_active())
            assert.is_true(job:is_completed())
            t:expect(8)
            async.join(job)
            t:finish(9)
        end)
    )

    -- not-applicable: luastd exposes on_cancel but has no invokeOnCompletion
    -- callback for a lazily started job's normal completion.
    pending("testInvokeOnCompletionAndStart")
end)
